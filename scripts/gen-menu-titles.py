#!/usr/bin/env python3
"""Regenerate electron/src/engine/menu-titles.js from Apple's own translation files.

Apple's web player titles its context-menu items in the page language, and ships one translation chunk
per language (music.apple.com/assets/translations~*.js). This collects the titles Adam needs to recognise
(pin, unpin, delete from library, add to playlist) from every chunk, so an item is recognised whatever
language the page is in. Needs network access; re-run it when Apple adds a language or renames a key.

    python3 scripts/gen-menu-titles.py
"""
import concurrent.futures as cf
import json
import re
import sys
import urllib.request
from pathlib import Path

BASE = 'https://music.apple.com'
UA = {'User-Agent': 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36',
      'Accept-Language': 'en'}
OUT = Path(__file__).resolve().parents[1] / 'electron/src/engine/menu-titles.js'

KEYS = {
    'pin': ['ASE.Web.Music.Pins.ContextMenu.Pin.' + kind for kind in ('album', 'song', 'playlist', 'musicVideo')],
    'unpin': ['ASE.Web.Music.Pins.ContextMenu.Unpin.' + kind for kind in ('album', 'song', 'playlist', 'musicVideo')],
    'delete-from-library': ['ASE.Web.Music.Shared.ContextualMenu.DeleteFromLibrary'],
    'add-to-playlist': ['ASE.Web.Music.ContextualMenu.AddToPlaylist'],
}


def fetch(path):
    req = urllib.request.Request(path if path.startswith('http') else BASE + path, headers=UA)
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode('utf-8', 'replace')


def normalize(title):
    """Must match normalizeTitle in electron/src/engine/menu-action.js."""
    return re.sub(r'\s+', ' ', title.replace('­', '').replace(' ', ' ')).strip().lower()


def decode(raw):
    try:
        return json.loads('"' + raw + '"')
    except ValueError:
        return raw


def main():
    html = fetch('/it/home')
    index = re.search(r'/assets/index~[A-Za-z0-9_-]+\.js', html)
    if not index:
        sys.exit('could not find the main script in the page')
    names = sorted(set(re.findall(r'translations~[A-Za-z0-9_-]+\.js', fetch(index.group(0)))))
    if not names:
        sys.exit('no translation chunks referenced by the main script')
    with cf.ThreadPoolExecutor(8) as ex:
        chunks = list(ex.map(lambda n: fetch('/assets/' + n), names))
    titles = {action: set() for action in KEYS}
    seen = 0
    for text in chunks:
        found = False
        for action, keys in KEYS.items():
            for key in keys:
                m = re.search(r'"' + re.escape(key) + r'"\s*:\s*"((?:[^"\\]|\\.)*)"', text)
                if m:
                    titles[action].add(normalize(decode(m.group(1))))
                    found = True
        seen += found
    if seen < 20:
        sys.exit(f'only {seen} of {len(chunks)} chunks had the keys: Apple has renamed them')
    body = ',\n'.join(f"    {json.dumps(a)}: {json.dumps(sorted(v), ensure_ascii=False)}" for a, v in titles.items())
    OUT.write_text(
        "// Generated by scripts/gen-menu-titles.py from Apple's translation files. Do not edit by hand.\n"
        f"// {seen} languages. Titles are normalised (soft hyphens removed, spaces collapsed, lower case).\n"
        "export const MENU_TITLES = {\n" + body + ',\n};\n', encoding='utf-8')
    print(f'{OUT}: {seen} chunks, ' + ', '.join(f'{a}={len(v)}' for a, v in titles.items()))


if __name__ == '__main__':
    main()
